import * as fs from "node:fs";
import { capture, SESSIONS, test } from "./outils";
test.use({ viewport: { width: 1440, height: 1300 }, storageState: SESSIONS.admin });
const SORTIE = "C:/Users/diano/AppData/Local/Temp/claude/c--wamp64-www-ifspa/24e60f51-8504-4a57-ab00-c16a267ad84f/scratchpad/refus.txt";
test("sonde", async ({ page }) => {
  const notes: string[] = [];
  await page.goto("/app/parametres/frais");
  await page.getByRole("button", { name: "Nouveau frais" }).first().click();
  const d = page.getByRole("dialog", { name: "Nouveau frais" });
  await d.getByLabel("Libellé").fill("A");
  await d.getByLabel("Montant par étudiant (Ar)").fill("0");
  await page.waitForTimeout(500);
  notes.push("A/0/aucune classe: " + (await d.innerText()).replace(/\n+/g, " | "));
  await capture(page, "zz-sonde", "r1");
  await d.getByLabel("Libellé").fill("Frais test");
  await d.getByRole("checkbox", { name: "IF 1re année" }).check();
  await page.waitForTimeout(1200);
  notes.push("0 + classe: " + (await d.innerText()).replace(/\n+/g, " | "));
  await capture(page, "zz-sonde", "r2");
  await d.getByLabel("Montant par étudiant (Ar)").fill("15000,50");
  await d.getByLabel("Libellé").click();
  await page.waitForTimeout(1200);
  notes.push("decimal: " + (await d.innerText()).replace(/\n+/g, " | "));
  await capture(page, "zz-sonde", "r3");
  await d.getByLabel("Montant par étudiant (Ar)").fill("");
  await d.getByLabel("Libellé").click();
  await page.waitForTimeout(800);
  notes.push("vide: " + (await d.innerText()).replace(/\n+/g, " | "));
  await d.getByRole("button", { name: "Annuler" }).click();
  await page.getByRole("combobox", { name: "Année scolaire" }).click();
  await page.getByRole("option", { name: /^2025-2026/ }).click();
  await page.waitForTimeout(2500);
  notes.push("2025: " + (await page.locator("main").innerText()).replace(/\n+/g, " | "));
  await capture(page, "zz-sonde", "r4");
  fs.writeFileSync(SORTIE, notes.join("\n\n"));
});
